def get_mock_tdra_commits() -> list[dict]:
    """Return the mock commit list (newest first)."""
    return list(reversed(_MOCK_COMMITS))


def get_mock_risk_summary() -> dict:
    commits = _MOCK_COMMITS
    rf_scores = [c["risk_factor"] for c in commits]
    critical = [c for c in commits if c["severity"] == "Critical"]
    high = [c for c in commits if c["severity"] == "High"]
    riskiest = max(commits, key=lambda c: c["risk_factor"])
    return {
        "total_commits_analyzed": len(commits),
        "critical_commits": critical,
        "high_commits": high,
        "riskiest_commit": riskiest,
        "avg_risk_factor": round(sum(rf_scores) / len(rf_scores), 4),
        "total_new_paths_introduced": sum(c["new_attack_paths"] for c in commits),
        "total_guard_weakening_events": sum(c["guard_weakening_events"] for c in commits),
        "mock": True,
    }
